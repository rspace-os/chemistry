package com.researchspace.chemistry.analysis;

/**
 * Enum representing the different types of chemical analysis that can be performed.
 */
public enum AnalysisType {
  /**
   * Extraction analysis, which extracts information about molecules and their properties.
   */
  EXTRACTION,

  /**
   * Stoichiometry analysis, which analyzes the quantitative relationships between reactants and products in a chemical reaction.
   */
  STOICHIOMETRY
}